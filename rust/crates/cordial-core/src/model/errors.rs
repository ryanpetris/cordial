#[serde(rename_all = "snake_case")]
pub enum ErrorCode {
    UnknownCommand,
    InvalidArgs,
    Busy,
    NotFound,
    Blocked,
    CandidateExpired,
    Disabled,
    Capacity,
    UnsupportedHid,
    HidReportTooLarge,
    UnsupportedTransport,
    AuthenticationFailed,
    AuthenticationRejected,
    StalePrompt,
    ConnectionFailed,
    RadioUnavailable,
    InputOverflow,
    StorageFailed,
    StorageFull,
    Timeout,
    Cancelled,
    NotPending,
    InternalError,
    NotConnected,
    /// A saved preference refers to the profile.
    InUse,
    ReadOnly,
    HidppDisabled,
    SettingsUnavailable,
    UnsupportedSetting,
    SettingsLimit,
    FeatureSetUnavailable,
    ReadbackMismatch,
    BacklightModeSelectionRequired,
    BacklightPermanentManualRequired,
    NativeRoutingRequired,
    NativeStandardResolutionRequired,
    HidppReportsUnavailable,
    HidppProtocolUnsupported,
    HidppResetUnavailable,
    HidppControlsUnavailable,
    HidppTimeout,
    HidppTransportError,
    HidppDeviceError,
    HidppInvalidResponse,
}
