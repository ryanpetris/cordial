// Generates current serial messages, the permanent handshake, migration IPC and storage messages.
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, existsSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { fromBinary } from "@bufbuild/protobuf";
import { FileDescriptorSetSchema } from "@bufbuild/protobuf/wkt";
import { fingerprint } from "./fingerprint.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const proto = join(root, "../../../proto");
const check = process.argv.includes("--check");
const version = Number(readFileSync(join(proto, "serial/current"), "utf8").trim());
if (!Number.isInteger(version) || version <= 0 || version > 0xffffffff) throw new Error("invalid current protocol revision");
const serial = `serial/v${version}/cordial.proto`;
const temporary = mkdtempSync(join(tmpdir(), "cordial-protocol-"));
function output(path, text) {
  text = text.trimEnd() + "\n";
  const file = join(root, path);
  if (!check) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
  } else if (!existsSync(file) || readFileSync(file, "utf8") !== text) {
    console.error(`${path} is out of date; run npm run generate`);
    process.exitCode = 1;
  }
}
function files(directory) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? files(path) : [path];
  });
}
try {
  const paths = [join(proto, serial), ...files(proto).filter(path => path.endsWith(".proto") && !path.startsWith(join(proto, "serial") + "/"))];
  execFileSync("buf", ["generate", proto, "--include-imports", ...paths.flatMap(path => ["--path", path]), "--config", join(root, "buf.yaml"), "--template", join(root, "buf.gen.yaml"), "--output", temporary], { cwd: root, stdio: "inherit" });
  const generated = new Set(["src/gen/cordial_pb.ts"]);
  for (const file of files(join(temporary, "src/gen"))) {
    const path = file.slice(temporary.length + 1);
    generated.add(path);
    output(path, readFileSync(file, "utf8"));
  }
  const serialOutput = join(root, "src/gen/serial");
  if (existsSync(serialOutput)) {
    for (const entry of readdirSync(serialOutput, { withFileTypes: true })) {
      if (!entry.isDirectory() || [...generated].some(path => path.startsWith(`src/gen/serial/${entry.name}/`))) continue;
      if (check) {
        console.error(`src/gen/serial/${entry.name} is stale; run npm run generate`);
        process.exitCode = 1;
      } else {
        rmSync(join(serialOutput, entry.name), { recursive: true });
      }
    }
  }
  for (const file of files(join(root, "src/gen"))) {
    const path = file.slice(root.length);
    if (generated.has(path)) continue;
    if (check) {
      console.error(`${path} is out of date; run npm run generate`);
      process.exitCode = 1;
    } else {
      rmSync(file);
    }
  }
  // Keep the established generated import and file descriptor export available.
  output("src/gen/cordial_pb.ts", `// Current operational schema. Generated by scripts/generate.mjs.\nexport * from "./serial/v${version}/cordial_pb.ts";\nexport { file_serial_v${version}_cordial as file_cordial } from "./serial/v${version}/cordial_pb.ts";\n`);
  for (const entry of readdirSync(join(proto, "serial"), { withFileTypes: true })) {
    if (!entry.isDirectory() || !/^v[1-9][0-9]*$/.test(entry.name)) continue;
    const schema = `serial/${entry.name}/cordial.proto`;
    const descriptors = fromBinary(FileDescriptorSetSchema, execFileSync("buf", ["build", proto, "--path", join(proto, schema), "--as-file-descriptor-set", "--config", join(root, "buf.yaml"), "-o", "-"], { cwd: root }));
    const digest = fingerprint(descriptors);
    output(`../../../proto/serial/${entry.name}/schema.sha256`, `${digest}\n`);
    if (entry.name === `v${version}`) {
      output("src/current.ts", `// Generated by scripts/generate.mjs.\nexport const CURRENT_PROTOCOL_VERSION = ${version};\n/** SHA-256 of the normalized operational descriptor set. */\nexport const OPERATIONAL_SCHEMA_SHA256 = "${digest}";\n`);
    }
  }
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
